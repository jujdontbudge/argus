/**
 * Ticket #92's evidence artifact — `docs/acceptance/batch-and-search.txt`.
 *
 * Written BEFORE the assertions run, so a failed run still leaves the file
 * that explains why. #82's lesson, restated: a GitHub comment is not evidence
 * and a passing test that left no artifact cannot be re-read six weeks later.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import {
  BATCH_TICKETS,
  SPEC_BULLET_2,
  SPEC_BULLET_4,
  SPEC_SECTION_14_HEADING,
  type BatchSearchReport,
} from "./batch-search.ts";

const EVIDENCE = fileURLToPath(
  new URL("../../docs/acceptance/batch-and-search.txt", import.meta.url),
);

function hash(text: string): string {
  const hasher = new Bun.CryptoHasher("sha256");
  hasher.update(text);
  return hasher.digest("hex");
}

const rule = (title: string): string =>
  ["", "=".repeat(78), title, "=".repeat(78), ""].join("\n");

export function renderBatchEvidence(report: BatchSearchReport): string {
  const out: string[] = [];

  out.push("SPEC §14 bullets 2 and 4, driven live — ticket #92");
  out.push("");
  out.push(
    "Generated by src/harness/batch-search.ts behind ARGUS_LIVE_BATCH_SEARCH=1.",
  );
  out.push(`sandbox root : ${report.sandboxRoot}`);
  out.push(`sandbox repo : ${report.repo}`);
  out.push(`argus up     : exit ${report.upExitCode}`);

  out.push(rule("THE TWO BULLETS, VERBATIM FROM SPEC.md"));
  out.push(`${SPEC_SECTION_14_HEADING}`);
  out.push("");
  out.push("Bullet 2 (the concurrency claim):");
  out.push("");
  out.push(SPEC_BULLET_2);
  out.push("");
  out.push("Bullet 4 (the search claim):");
  out.push("");
  out.push(SPEC_BULLET_4);
  out.push("");
  out.push(
    [
      "WHERE THE TICKET AND THE SPEC DIFFER — #89's warning, and it applies again.",
      "",
      "  1. LINE NUMBERS. #92 cites SPEC.md:707-708 for bullet 2 and SPEC.md:730 for",
      "     bullet 4. §14 does not begin until SPEC.md:763. The cited range falls",
      "     inside §13 (the fake-Johan harness). The bullets are at 768-769 and 791.",
      "",
      "  2. WORDING, and it changes the meaning. #92 renders bullet 2's tail as",
      '     "USER.md gains nothing BECAUSE Johan typed nothing". The SPEC says',
      '     "USER.md gains **nothing** UNLESS Johan actually typed". The SPEC states a',
      "     GATE — only Johan's own typing may write that file — which is a property of",
      "     the pipeline. The ticket's wording states an ABSENCE — nobody typed, so",
      "     nothing arrived — which is a property of this particular run and would be",
      "     satisfied by a pipeline with no gate in it at all.",
      "",
      "     This run asserts the bytes are identical, which is what a run with no human",
      "     in it can honestly show. It does NOT exercise the gate's other side (Johan",
      "     types, USER.md learns); that is §13 slot 2's business and it is not claimed",
      "     here.",
      "",
      "  3. SCALE. The SPEC says a 10-ticket batch. This ran FIVE. Three-at-a-time",
      "     against a cap of three is what the concurrency clause tests; tickets four",
      "     and five prove the cap released and refilled. The shortfall is stated here",
      "     rather than left to look like ten.",
      "",
      '  4. "every ticket a fresh attachable cmux session" is NOT COVERED by this run.',
      "     No cmux verb ran at all — see the refusals section at the end.",
    ].join("\n"),
  );

  out.push(rule("1. THE SLOT TIMELINE — the cap held"));
  out.push(
    [
      "Two readings. Neither is a counter this test kept.",
      "",
      "  STRUCTURAL. src/dispatch/slots.ts builds exactly maxConcurrency slot paths",
      "  (slot-0 .. slot-(n-1)) and takes each with an exclusive `wx` open. A fourth",
      "  simultaneous holder has nowhere to go. This is the cap; everything below is",
      "  a check on it.",
      "",
      "  THE FILES' OWN TIMESTAMPS. `acquiredAt` is a field the slot file wrote about",
      "  itself; `birthtime` is the filesystem's. `observed`/`vanished` are this",
      "  harness's polling stamps and are labelled as such — the slot file is UNLINKED",
      "  on release, so no file records its own release time and the disappearance can",
      "  only ever be an observation.",
      "",
      `  poller samples: ${report.timeline.samples}` +
        `   peak distinct slot files seen at once: ${report.timeline.peakConcurrentFiles}`,
      "",
    ].join("\n"),
  );
  for (const occupancy of report.timeline.occupancies) {
    out.push(
      `  ${occupancy.slot}  ticket #${occupancy.ticket.padEnd(4)} state=${occupancy.state.padEnd(9)} pid=${String(occupancy.pid).padEnd(7)}`,
    );
    out.push(`      acquiredAt (file's own)  ${occupancy.acquiredAt}`);
    out.push(`      birthtime  (filesystem)  ${occupancy.birthtime}`);
    out.push(
      `      observed   (harness)     ${occupancy.firstObserved} .. ${occupancy.lastObserved}`,
    );
    out.push(
      `      vanished   (harness)     ${occupancy.vanishedObserved ?? "(still present at teardown)"}`,
    );
    if (occupancy.sessionId !== undefined) {
      out.push(`      session                  ${occupancy.sessionId}`);
    }
    if (occupancy.worktree !== undefined) {
      out.push(`      worktree                 ${occupancy.worktree}`);
    }
  }

  out.push("");
  out.push("  Per-slot occupancy order (a path can only be retaken after an unlink):");
  const bySlot = new Map<string, string[]>();
  for (const occupancy of report.timeline.occupancies) {
    bySlot.set(occupancy.slot, [
      ...(bySlot.get(occupancy.slot) ?? []),
      `#${occupancy.ticket}@${occupancy.acquiredAt}`,
    ]);
  }
  for (const [slot, occupants] of [...bySlot].sort()) {
    out.push(`    ${slot}: ${occupants.join("  ->  ")}`);
  }

  out.push("");
  out.push("  The dispatch passes:");
  for (const pass of report.passes) {
    out.push(
      `    ${pass.label}: tracker=${pass.report.tracker} cap=${pass.report.maxConcurrency} ` +
        `inFlight=${pass.report.inFlight} dispatched=[${pass.report.dispatched.map((entry) => `#${entry.ticket}`).join(", ")}]`,
    );
    for (const excluded of pass.report.excluded) {
      out.push(`      excluded #${excluded.number}: ${excluded.reason} — ${excluded.detail}`);
    }
    for (const recovered of pass.report.recovered) {
      out.push(`      recovered #${recovered.ticket}: ${recovered.outcome} — ${recovered.detail}`);
    }
    for (const skipped of pass.report.skipped) {
      out.push(`      skipped #${skipped.ticket}: ${skipped.reason}`);
    }
    for (const degraded of pass.report.degraded) {
      out.push(`      DEGRADED: ${degraded}`);
    }
    out.push(
      `      fake tracker after this pass: ${pass.tracker
        .map(
          (issue) =>
            `#${issue.number}=${issue.state}${issue.assignees.length > 0 ? `/${issue.assignees.join("+")}` : "/unassigned"}`,
        )
        .join("  ")}`,
    );
    out.push(`      gh calls issued so far: ${pass.ghCalls.length}`);
  }

  const afterFirst = report.passes[0]?.tracker ?? [];
  const refused = afterFirst.filter((issue) => issue.assignees.length === 0);
  out.push(
    [
      "",
      "  READ THIS BEFORE READING THE COUNTS. Pass 1 had FIVE dispatchable tickets in",
      "  front of it and started THREE. The two it refused are NOT in `excluded` —",
      "  the loop broke on `inFlight >= maxConcurrency` before `claimTicket` was ever",
      "  called on them, so on the tracker they are simply still open and still",
      "  unassigned. That is where the refusal is visible, and it is the cap doing its",
      "  job rather than a frontier that never offered them:",
      "",
      `    open and STILL UNASSIGNED after pass 1: ${refused.map((issue) => `#${issue.number}`).join(", ") || "(none)"}`,
      `    claimed by pass 1:                      ${afterFirst
        .filter((issue) => issue.assignees.length > 0)
        .map((issue) => `#${issue.number}`)
        .join(", ") || "(none)"}`,
      "",
      "    No `gh issue edit --add-assignee` was issued for the refused tickets in pass",
      "    1; the full argv list per pass is counted above and the fake tracker is the",
      "    only tracker this run ever touched.",
    ].join("\n"),
  );

  out.push(rule("2. FIVE TICKETS, FIVE WORKTREES, FIVE SESSIONS, TWO AGENTS"));
  out.push(
    "  ticket  agent   session id                            worktree / branch",
  );
  for (const entry of report.dispatched) {
    out.push(`  #${entry.ticket.padEnd(6)} ${entry.agent.padEnd(7)} ${entry.sessionId}`);
    out.push(`          ${entry.worktree}`);
    out.push(`          branch ${entry.branch}`);
    if (entry.workspaceDegraded !== undefined) {
      out.push(`          no cmux tab: ${entry.workspaceDegraded}`);
    }
  }

  out.push("");
  out.push(
    [
      "  THE PROCESSES THEMSELVES — concurrency evidence that does not come from the",
      "  slot files at all. Wall-clock start and exit per worker; overlapping",
      "  intervals are three real sessions in flight at once.",
      "",
    ].join("\n"),
  );
  for (const worker of report.workers) {
    out.push(
      `  ${worker.agent.padEnd(7)} pid=${String(worker.pid ?? -1).padEnd(7)} exit=${String(worker.exitCode ?? "?").padEnd(4)} ${worker.startedAt} .. ${worker.exitedAt ?? "(never observed exiting)"}`,
    );
    out.push(`      cwd   ${worker.cwd}`);
    out.push(`      HOME  ${worker.home}`);
    if (worker.claudeConfigDir !== undefined) {
      out.push(`      CLAUDE_CONFIG_DIR ${worker.claudeConfigDir}`);
    }
    if (worker.codexHome !== undefined) {
      out.push(`      CODEX_HOME ${worker.codexHome}`);
    }
    out.push(`      argv  ${worker.argv.join(" ")}`);
    const reply = (worker.stdout ?? "").trim();
    out.push(
      `      stdout(${reply.length}b) ${reply.length > 900 ? `${reply.slice(0, 450)} … ${reply.slice(-450)}` : reply}`,
    );
    const err = (worker.stderr ?? "").trim();
    if (err !== "") out.push(`      stderr ${err.slice(0, 400)}`);
  }

  out.push("");
  out.push(
    [
      "  #89's check, structurally. The Claude legs' transcripts are relocated out of",
      "  the real ~/.claude/projects/ using a slug derived from the DEPLOYMENT'S OWN",
      "  worktree path. A session that had run in Johan's real ~/argus — the",
      "  regression #89 fixed on the grill path — would produce zero files here.",
      `  Relocated transcript files: ${report.relocatedTranscripts}`,
      `  Sessions production's own repo-scoped source could see: ${report.visibleSessions.length}`,
      ...report.visibleSessions.map((session) => `    ${session}`),
    ].join("\n"),
  );

  out.push(rule("3. THE ARCHIVE — every message, attributed, across concurrent writers"));
  const watchers = report.watcherStatus?.watchers ?? [];
  out.push(`  watchers started: ${watchers.length}`);
  for (const watcher of watchers) {
    out.push(`    ${watcher.eye.padEnd(9)} pid=${watcher.pid}  repo=${watcher.repo}`);
  }
  out.push("");
  out.push(`  archive_messages rows: ${report.archived.length}`);
  out.push("");
  for (const entry of report.dispatched) {
    const ticket = BATCH_TICKETS.find((candidate) => candidate.number === entry.ticket)!;
    const rows = report.archived.filter((row) => row.sessionId === entry.sessionId);
    out.push(`  session ${entry.sessionId}  (ticket #${entry.ticket}, ${entry.agent})`);
    out.push(`    token this session alone should carry: ${ticket.token}`);
    if (rows.length === 0) {
      out.push("    NO ROWS — see #96 (a session with a durable registry row, five");
      out.push("    watchers, and no transcript) before suspecting the eyes.");
      continue;
    }
    for (const row of rows) {
      const text = row.content.replace(/\s+/g, " ").trim();
      out.push(
        `    ${row.ts}  role=${row.role.padEnd(9)} provenance=${row.provenance.padEnd(7)} via=${row.via.padEnd(16)} agent=${row.agent ?? "null"} ticket=${row.ticket ?? "null"}`,
      );
      out.push(`      ${text.length > 300 ? `${text.slice(0, 300)}…` : text}`);
    }
    const strays = report.archived.filter(
      (row) => row.sessionId !== entry.sessionId && row.content.includes(ticket.token),
    );
    out.push(
      `    rows in ANY OTHER session carrying this token: ${strays.length}` +
        (strays.length === 0 ? "  (nothing misattributed)" : "  <-- MISATTRIBUTION"),
    );
  }

  out.push(rule("4. USER.md — byte-identical, because Johan typed nothing"));
  out.push(`  path   ${report.userMdPath}`);
  out.push(`  before sha256 ${hash(report.userMdBefore)}  (${report.userMdBefore.length} bytes)`);
  out.push(`  after  sha256 ${hash(report.userMdAfter)}  (${report.userMdAfter.length} bytes)`);
  out.push(
    `  identical: ${report.userMdBefore === report.userMdAfter ? "YES" : "NO <-- FINDING"}`,
  );
  out.push("");
  out.push(
    [
      "  What this does and does not show. It shows the bytes did not move across five",
      "  live sessions with the real reviewer watcher running over them. It does NOT",
      "  exercise the other side of the SPEC's gate — Johan types and USER.md learns —",
      "  which is §13 slot 2's job and is not claimed here.",
    ].join("\n"),
  );

  out.push(rule("5. SPEC §14 BULLET 4 — `argus search`, the CLI, across two agents"));
  out.push(
    [
      "  WHICH BOUNDARY THE SEARCH CROSSED, stated exactly, because this is the bullet",
      "  that is easy to fake:",
      "",
      "    - a DIFFERENT PROCESS. `argus search` is spawned as its own `bun src/cli.ts",
      "      search` child. It shares no memory, no connection and no handle with the",
      "      run. src/search/search.test.ts calls openArchiveSearch in-process against a",
      "      DB it built in-process; that is the boundary this deliberately does not use.",
      "    - AFTER EVERY WRITER EXITED. All five agent processes had exited and all five",
      "      watcher processes had been stopped before the first query ran. The store is",
      "      read back off disk, not observed mid-write.",
      "    - ACROSS TWO AGENTS AND TWO SESSIONS. One query retrieves a codex session's",
      "      reply, the other a claude session's. Both tickets were dispatched in the",
      "      SAME three-at-a-time pass, so the retrieval crosses the concurrent part of",
      "      the batch rather than its serialized tail.",
      "    - THE AGENT'S OWN WORDS, not the harness's echo. The token is spelled in two",
      "      halves in the dispatch prompt and joined by the agent, so a query for the",
      "      whole token cannot match the archived prompt.",
      "",
    ].join("\n"),
  );
  for (const invocation of report.searches) {
    out.push(`  $ cd ${invocation.cwd}`);
    out.push(`  $ ${invocation.argv.slice(1).join(" ")}`);
    out.push(`  exit ${invocation.exitCode}`);
    for (const line of invocation.stdout.split("\n")) out.push(`  | ${line}`);
    if (invocation.stderr.trim() !== "") {
      for (const line of invocation.stderr.split("\n")) out.push(`  ! ${line}`);
    }
    out.push("");
  }

  out.push(rule("FLEET RSS — Directive 14"));
  out.push(
    `  peak total resident set across live watchers + agent processes: ${report.peakFleetRssMb} MB`,
  );
  out.push(`  samples with at least one live process: ${report.fleetSamples.length}`);
  for (const sample of report.fleetSamples) {
    out.push(`    ${sample.at}  processes=${sample.processes}  rss=${sample.rssMb} MB`);
  }

  out.push(rule("NOTES, STAND-INS AND REFUSALS"));
  out.push(
    [
      "  THE ONE HARNESS INTERVENTION IN THE MIDDLE OF THE BATCH, and why the ticket's",
      "  stated design could not have worked without it.",
      "",
      "  src/dispatch/recover.ts grades a dead session by what it left behind. A",
      '  session that produced "one bounded scripted reply and nothing else" — #92\'s',
      "  own words — leaves a CLEAN worktree and no commits, which production grades",
      "  `returned-to-frontier`: the claim is RELEASED, the worktree and branch are",
      "  DELETED, and the ticket goes back on the frontier. Pass 2 would then have",
      "  re-dispatched tickets 1-3, and tickets 4 and 5 would never have run — so the",
      "  refill #92 asks tickets four and five to prove could not have happened as the",
      "  ticket specifies it. Deleting the worktree would also break `repositoryFor()`,",
      "  so production's own repo-scoped source would drop every pass-1 transcript and",
      "  the archive assertions would fail for a reason with nothing to do with the",
      "  archiver.",
      "",
      "  So after each pass-1 session exited, the harness wrote ONE file into its",
      "  worktree, standing in for uncommitted work. That is the minimum that makes",
      "  production grade the slot `uncommitted-work` (claim stands, worktree",
      "  preserved, slot released). The release, the refill, the archive and the search",
      "  are all production's. This is the only place the harness touched the batch",
      "  between passes.",
      "",
      "  WHAT THIS RUN REFUSED TO DO:",
      "",
      "    - It created NO cmux workspace and NO cmux tab, and ran no cmux verb at all.",
      "      `createSandbox` strips CMUX_* from the child environment, so `openWorkerTab`",
      "      refuses at its first check (`no CMUX_WORKSPACE_ID`) before cmux is invoked.",
      "      Deployments proceeded without a tab, which is #7's standing rule. Bullet 2's",
      '      "every ticket a fresh attachable cmux session" is therefore NOT COVERED.',
      "      The refusal is deliberate: the tab is cosmetic to every assertion above, and",
      "      tearing five surfaces down through `close-surface` is the verb behind open",
      "      incident #98 — a pre-existing tab of Johan's that vanished. Three-way",
      "      concurrency is not where to re-run that experiment.",
      "    - It never wrote ~/.claude, ~/.claude.json, ~/.hermes, ~/.codex/config.toml or",
      "      any real project. ~/.claude/projects/ and ~/.codex/auth.json were READ only;",
      "      auth.json was copied into the sandbox's scratch CODEX_HOME, which teardown",
      "      removed. ~/.claude/.credentials.json was never opened.",
      "    - It ran no `claude setup-token`, no `/login`, no `logout`, no `claude auth`.",
      "      Both legs are subscription (SPEC §1 items 7-8).",
      "    - It changed no model, effort or default. The deploy routes' own settings",
      "      (claude opus max, codex high) are production's; the watcher brains stayed on",
      "      whatever `.argus/config.yaml` seeded (#54: luna@low).",
      "    - It did NOT run the merge/close leg. #92 puts it out of scope and #87 owns it.",
      "",
      "  RUN NOTES:",
    ].join("\n"),
  );
  for (const note of report.notes) out.push(`    - ${note}`);

  out.push("");
  return `${out.join("\n")}\n`;
}

export async function writeBatchEvidence(report: BatchSearchReport): Promise<string> {
  const text = renderBatchEvidence(report);
  await mkdir(new URL("../../docs/acceptance/", import.meta.url).pathname, {
    recursive: true,
  });
  await writeFile(EVIDENCE, text);
  return EVIDENCE;
}
